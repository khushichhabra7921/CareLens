"""Measure one heavy query with and without the indexes from sql/schema/004_indexes.sql,
and write both EXPLAIN ANALYZE plans into docs/ANALYSES.md.

"Without indexes" happens inside a transaction that drops them and is then ROLLED BACK,
so the real indexes are never removed. Each variant runs once to warm the cache, then
RUNS times; we report the median execution time.

Usage (full dataset loaded):  py -3.12 scripts/benchmark_indexes.py
"""

import re
import statistics

from psycopg import sql

from common import REPO_ROOT, SQL_DIR, connect

RUNS = 5
QUERY_FILE = SQL_DIR / "benchmarks" / "care_gap_bp.sql"
DOC = REPO_ROOT / "docs" / "ANALYSES.md"
BEGIN, END = "<!-- BEGIN index-benchmark (generated) -->", "<!-- END index-benchmark -->"


def index_names() -> list[str]:
    text = (SQL_DIR / "schema" / "004_indexes.sql").read_text(encoding="utf-8")
    return re.findall(r"CREATE INDEX IF NOT EXISTS (\w+)", text)


def measure(conn, query: str) -> tuple[float, str, tuple]:
    """Median execution time (ms), the plan text of the last run, and the query's result."""
    result = conn.execute(query).fetchone()  # warm-up run (loads pages into cache)
    times, plan = [], ""
    for _ in range(RUNS):
        rows = conn.execute("EXPLAIN (ANALYZE, BUFFERS, COSTS OFF) " + query).fetchall()
        plan = "\n".join(r[0] for r in rows)
        times.append(float(re.search(r"Execution Time: ([\d.]+) ms", plan).group(1)))
    return statistics.median(times), plan, result


def main() -> None:
    query = QUERY_FILE.read_text(encoding="utf-8")
    with connect("loader") as conn:
        conn.execute("SET timezone = 'UTC'")
        version = conn.execute("SHOW server_version").fetchone()[0]
        obs_rows = conn.execute("SELECT count(*) FROM analytics.observations").fetchone()[0]

        # 1) Without indexes: drop inside a transaction, measure, roll back.
        with conn.transaction(force_rollback=True):
            for name in index_names():
                conn.execute(sql.SQL("DROP INDEX analytics.{}").format(sql.Identifier(name)))
            conn.execute("ANALYZE analytics.observations")
            before_ms, before_plan, before_result = measure(conn, query)

        # 2) With indexes (they're back, because the transaction above was rolled back).
        conn.execute("ANALYZE analytics.observations")
        after_ms, after_plan, after_result = measure(conn, query)

    if before_result != after_result:
        raise SystemExit(f"Results differ! {before_result} vs {after_result}")

    result_line = (f"Result (identical both ways): {after_result[0]:,} hypertensive patients, "
                   f"{after_result[1]:,} without a reading.")
    setup_line = (f"**Setup:** PostgreSQL {version}, local Docker, {obs_rows:,} observation "
                  f"rows. Median of {RUNS} warm runs.")
    section = f"""{BEGIN}
_Generated by `scripts/benchmark_indexes.py`. Do not edit by hand._

**Query:** `sql/benchmarks/care_gap_bp.sql`: hypertensive patients with no systolic blood
pressure reading in the 12 months before the reference date.
{result_line}

{setup_line}

| | Median execution time |
|---|---|
| Without indexes | {before_ms:,.1f} ms |
| With indexes (`ix_observations_code_patient_date`) | {after_ms:,.1f} ms |
| Speed-up | {before_ms / after_ms:,.0f}x |

<details><summary>Plan without indexes</summary>

```
{before_plan}
```
</details>

<details><summary>Plan with indexes</summary>

```
{after_plan}
```
</details>
{END}"""

    doc = DOC.read_text(encoding="utf-8") if DOC.exists() else "# Analyses\n"
    if BEGIN in doc:
        doc = doc[: doc.index(BEGIN)] + section + doc[doc.index(END) + len(END):]
    else:
        doc += "\n## Index benchmark\n\n" + section + "\n"
    DOC.write_text(doc, encoding="utf-8", newline="\n")
    print(f"Without indexes: {before_ms:.1f} ms | with: {after_ms:.1f} ms "
          f"({before_ms / after_ms:.0f}x). Written to {DOC.relative_to(REPO_ROOT)}.")


if __name__ == "__main__":
    main()
